#!/usr/bin/env python3
"""Give fullrust a C symbol for every function of the in-tree pure-Rust libm.

compiler-builtins compiles rust-lang's libm (`library/compiler-builtins/libm`)
into every program but gives only part of it a C name (`sin`, `pow`, ...).
fullrust has no C libm, and its LLVM target is `x86_64-unknown-linux-gnu`, so
anything else -- LLVM folding `sin`+`cos` into `sincos`, or a crate declaring
`extern "C" { fn frexp(..); }` -- failed to link. This rewrites the fullrust
block in `compiler-builtins/src/math/mod.rs` of one rust-<minor> checkout so it
exports every libm function compiler-builtins doesn't already, with the C
signature (tuple returns become out-pointers, as in C).

The list comes from that version's own libm and compiler-builtins, so it is
right for each version without hand-maintenance.

Usage:  ./gen-libm-exports.py rust-1.100      (then ./regen-overlay.sh 1.100)
"""
import pathlib
import re
import sys

BEGIN = "    // BEGIN fullrust libm exports (generated by toolchain/gen-libm-exports.py)\n"
END = "    // END fullrust libm exports\n"
ANCHOR = "pub mod partial_availability {\n"

def libm_exports(libm: pathlib.Path) -> set[str]:
    mod = (libm / "src/math/mod.rs").read_text()
    names = set()
    for m in re.finditer(r"pub use self::[a-z0-9_]+::(\{[^}]*\}|[a-z0-9_]+);", mod):
        for n in m.group(1).strip("{}").split(","):
            n = n.strip()
            if n:
                names.add(n)
    return names


def already_exported(math_mod: str) -> set[str]:
    # Everything compiler-builtins defines itself, outside our generated block.
    text = re.sub(re.escape(BEGIN) + r".*?" + re.escape(END), "", math_mod, flags=re.S)
    return set(re.findall(r"\bfn ([a-z0-9_]+)\(", text))


def signature(libm: pathlib.Path, name: str):
    """(args [(name, type)], ret) of `pub fn <name>` in libm's sources."""
    pat = re.compile(r"pub (?:const )?fn " + re.escape(name) + r"\(([^)]*)\)\s*->\s*([^{]+?)\s*\{")
    for f in sorted((libm / "src/math").rglob("*.rs")):
        m = pat.search(f.read_text())
        if m:
            args = []
            for a in filter(None, (x.strip() for x in m.group(1).split(","))):
                an, at = a.split(":")
                args.append((an.replace("mut ", "").strip(), at.strip()))
            return args, m.group(2).strip()
    raise SystemExit(f"no `pub fn {name}` in {libm}")


def cfg_for(types: str) -> str:
    c = []
    if "f16" in types:
        c.append("f16_enabled")
    if "f128" in types:
        c.append("f128_enabled")
    return "" if not c else (f"#[cfg({c[0]})]" if len(c) == 1 else f"#[cfg(all({', '.join(c)}))]")


def wrapper(name: str, args, ret) -> str:
    params = ", ".join(f"{n}: {t}" for n, t in args)
    call = f"super::libm_math::{name}({', '.join(n for n, _ in args)})"
    tup = re.fullmatch(r"\((\w+),\s*(\w+)\)", ret)
    if not tup:
        return f"pub extern \"C\" fn {name}({params}) -> {ret} {{\n    {call}\n}}"
    a, b = tup.groups()
    if name.startswith("sincos"):
        # void sincos(x, *sin, *cos)
        return (f"pub extern \"C\" fn {name}({params}, s: &mut {a}, c: &mut {b}) {{\n"
                f"    (*s, *c) = {call};\n}}")
    if name.startswith("modf"):
        # fractional part returned, integral part stored
        return (f"pub extern \"C\" fn {name}({params}, iptr: &mut {b}) -> {a} {{\n"
                f"    let (frac, int) = {call};\n    *iptr = int;\n    frac\n}}")
    if name.startswith(("frexp", "remquo")) and b == "i32":
        # frexp(x, *exp) / remquo(x, y, *quo): value returned, int stored
        return (f"pub extern \"C\" fn {name}({params}, n: &mut i32) -> {a} {{\n"
                f"    let (r, i) = {call};\n    *n = i;\n    r\n}}")
    raise SystemExit(f"don't know the C shape of {name} -> {ret}")


def main(tree: str) -> None:
    root = pathlib.Path(tree)
    libm = root / "library/compiler-builtins/libm"
    math_path = root / "library/compiler-builtins/compiler-builtins/src/math/mod.rs"
    math_mod = math_path.read_text()

    missing = sorted(libm_exports(libm) - already_exported(math_mod))
    groups: dict[str, list[str]] = {}
    for name in missing:
        args, ret = signature(libm, name)
        cfg = cfg_for(ret + " ".join(t for _, t in args))
        groups.setdefault(cfg, []).append(wrapper(name, args, ret))

    out = [BEGIN,
           "    // fullrust has no C libm, and its LLVM target is `x86_64-unknown-linux-gnu`,\n",
           "    // so LLVM and crates assume glibc's full libm (e.g. LLVM folds `sin`+`cos`\n",
           "    // into `sincos`). Give every remaining function of this pure-Rust libm its C\n",
           "    // name, with the C signature. This crate is `no_builtins`, so none of these\n",
           "    // can be folded back into a call to itself.\n"]
    for cfg in sorted(groups):
        attrs = '#[cfg(target_os = "fullrust")]' if not cfg else \
            cfg.replace("#[cfg(", '#[cfg(all(target_os = "fullrust", ').replace(")]", "))]")
        out.append(f"    {attrs}\n    intrinsics! {{\n")
        body = "\n\n".join(groups[cfg])
        out.append("".join(f"        {l}\n" if l else "\n" for l in body.split("\n")))
        out.append("    }\n\n")
    out[-1] = out[-1].rstrip("\n") + "\n"
    out.append(END)
    block = "".join(out)

    if BEGIN in math_mod:
        math_mod = re.sub(re.escape(BEGIN) + r".*?" + re.escape(END), lambda _: block, math_mod, flags=re.S)
    else:
        assert math_mod.count(ANCHOR) == 1, math_path
        math_mod = math_mod.replace(ANCHOR, ANCHOR + block + "\n")
    math_path.write_text(math_mod)
    print(f"{tree}: {len(missing)} libm functions exported: {' '.join(missing)}")


if __name__ == "__main__":
    for t in sys.argv[1:] or sys.exit(__doc__):
        main(t)
